def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    locales_dir = os.path.join(root, "extension", "_locales")
    os.makedirs(locales_dir, exist_ok=True)
    
    total = len(LOCALES)
    print(f"Generating {total} locales in {locales_dir}...")
    
    for code, items in LOCALES.items():
        name_len = len(items["extName"])
        desc_len = len(items["extDescription"])
        
        if desc_len > 132:
            raise ValueError(f"Locale {code} description too long: {desc_len} chars > 132 limit!")
            
        loc_dir = os.path.join(locales_dir, code)
        os.makedirs(loc_dir, exist_ok=True)
        
        msg_json = {}
        for k, v in items.items():
            if k == "popupStatusFree":
                msg_json[k] = {
                    "message": v,
                    "placeholders": {
                        "c": { "content": "$1" },
                        "t": { "content": "$2" }
                    }
                }
            else:
                msg_json[k] = { "message": v }
                
        file_path = os.path.join(loc_dir, "messages.json")
        with open(file_path, "w", encoding="utf-8") as f:
            json.dump(msg_json, f, ensure_ascii=False, indent=2)
            f.write("\n")
            
        print(f"+ [{code:6}] Name ({name_len:2}) | Desc ({desc_len:3}) written.")
        
    print(f"\nSuccessfully generated and verified all {total} Chrome Web Store locales!")

if __name__ == "__main__":
    main()
